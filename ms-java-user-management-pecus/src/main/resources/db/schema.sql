-- =============================================================================
-- HackTheSnackDB schema (PostgreSQL 14+ / Supabase)
--
-- Source of truth for the database structure. Apply it once to an empty
-- database (Supabase: SQL editor, `psql`, or `supabase db push`); the API
-- runs with spring.jpa.hibernate.ddl-auto=validate and only checks that its
-- JPA entities match these tables.
--
-- Column naming (inherited from the original model):
--   PK_ / FK_  primary / foreign keys      DX_  text
--   DN_        numbers and booleans        DD_  dates
-- Every table carries the audit columns DN_ACTIVO (soft-delete flag),
-- DD_FECHA_CREACION, DN_USUARIO_CREADOR, DD_FECHA_MODIFICACION,
-- DN_USUARIO_MODIFICADOR.
--
-- The script is idempotent (IF NOT EXISTS everywhere), so re-running it is safe.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Catalogs: brand, category, subcategory
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS brand (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dx_name                varchar(100) NOT NULL,
    dx_description         varchar(255),
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

CREATE TABLE IF NOT EXISTS category (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dx_name                varchar(100) NOT NULL,
    dn_general_indicator   boolean,
    dn_milk_indicator      boolean,
    dn_meat_indicator      boolean,
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

CREATE TABLE IF NOT EXISTS subcategory (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dx_name                varchar(100) NOT NULL,
    fk_category_id         bigint       REFERENCES category (pk_id),
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

-- ---------------------------------------------------------------------------
-- Products and ingredients (ingredients are called "substances" in the model)
-- Names are stored upper-case by the API.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS product (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dx_name                varchar(100) NOT NULL,
    dx_description         varchar(255),
    fk_brand_id            bigint       REFERENCES brand (pk_id),
    fk_category_id         bigint       REFERENCES category (pk_id),
    fk_subcategory_id      bigint       REFERENCES subcategory (pk_id),
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

CREATE TABLE IF NOT EXISTS substance (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dx_name                varchar(100) NOT NULL,
    dx_description         varchar(255),
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

-- ---------------------------------------------------------------------------
-- recipe: which ingredients a product contains (one row per pair).
-- Rows are soft-deleted (dn_activo = false) when an ingredient is removed and
-- re-activated when it is added again.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recipe (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_product_id          bigint       NOT NULL REFERENCES product (pk_id),
    fk_substance_id        bigint       NOT NULL REFERENCES substance (pk_id),
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

-- ---------------------------------------------------------------------------
-- evaluation: one saved run of the recipe generator for a product.
-- result_item: the estimated share of every ingredient in that run.
-- The ingredient/recipe/mean/std columns on evaluation mirror its first
-- result item (kept for backwards compatibility).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS evaluation (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_product_id          bigint       NOT NULL REFERENCES product (pk_id),
    fk_substance_id        bigint       REFERENCES substance (pk_id),
    fk_recipe_id           bigint       REFERENCES recipe (pk_id),
    dn_ingredient_mean     double precision,
    dn_ingredient_std      double precision,
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

CREATE TABLE IF NOT EXISTS result_item (
    pk_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_evaluation_id       bigint       NOT NULL REFERENCES evaluation (pk_id) ON DELETE CASCADE,
    fk_product_id          bigint       NOT NULL REFERENCES product (pk_id),
    fk_substance_id        bigint       NOT NULL REFERENCES substance (pk_id),
    fk_recipe_id           bigint       REFERENCES recipe (pk_id),
    dn_ingredient_mean     double precision,
    dn_ingredient_std      double precision,
    dn_activo              boolean      NOT NULL DEFAULT true,
    dd_fecha_creacion      timestamp    NOT NULL DEFAULT now(),
    dn_usuario_creador     bigint       NOT NULL DEFAULT 1,
    dd_fecha_modificacion  timestamp,
    dn_usuario_modificador bigint
);

-- ---------------------------------------------------------------------------
-- Integrity and lookup indexes
-- ---------------------------------------------------------------------------
-- Names are unique among active rows (soft-deleted rows may reuse a name).
CREATE UNIQUE INDEX IF NOT EXISTS ux_brand_name_active       ON brand (dx_name)       WHERE dn_activo;
CREATE UNIQUE INDEX IF NOT EXISTS ux_category_name_active    ON category (dx_name)    WHERE dn_activo;
CREATE UNIQUE INDEX IF NOT EXISTS ux_subcategory_name_active ON subcategory (dx_name) WHERE dn_activo;
CREATE UNIQUE INDEX IF NOT EXISTS ux_product_name_active     ON product (dx_name)     WHERE dn_activo;
CREATE UNIQUE INDEX IF NOT EXISTS ux_substance_name_active   ON substance (dx_name)   WHERE dn_activo;
-- A product contains an ingredient at most once.
CREATE UNIQUE INDEX IF NOT EXISTS ux_recipe_pair_active      ON recipe (fk_product_id, fk_substance_id) WHERE dn_activo;

CREATE INDEX IF NOT EXISTS ix_recipe_product          ON recipe (fk_product_id);
CREATE INDEX IF NOT EXISTS ix_evaluation_product      ON evaluation (fk_product_id);
CREATE INDEX IF NOT EXISTS ix_result_item_evaluation  ON result_item (fk_evaluation_id);
CREATE INDEX IF NOT EXISTS ix_result_item_product     ON result_item (fk_product_id);
CREATE INDEX IF NOT EXISTS ix_result_item_substance   ON result_item (fk_substance_id);

-- ---------------------------------------------------------------------------
-- Supabase hardening: the tables live in the `public` schema, which Supabase
-- exposes through its auto-generated Data API. Enabling row level security
-- without any policy blocks the `anon` / `authenticated` API roles entirely;
-- the Spring API connects as the table owner and is not affected.
-- (On plain PostgreSQL these statements are harmless.)
-- ---------------------------------------------------------------------------
ALTER TABLE brand       ENABLE ROW LEVEL SECURITY;
ALTER TABLE category    ENABLE ROW LEVEL SECURITY;
ALTER TABLE subcategory ENABLE ROW LEVEL SECURITY;
ALTER TABLE product     ENABLE ROW LEVEL SECURITY;
ALTER TABLE substance   ENABLE ROW LEVEL SECURITY;
ALTER TABLE recipe      ENABLE ROW LEVEL SECURITY;
ALTER TABLE evaluation  ENABLE ROW LEVEL SECURITY;
ALTER TABLE result_item ENABLE ROW LEVEL SECURITY;

